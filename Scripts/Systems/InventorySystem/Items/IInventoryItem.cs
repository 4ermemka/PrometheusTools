namespace Assets.Shared.Systems.InventorySystem.Items
{
    /// <summary>
    /// Минимальный контракт объекта, который может находиться в инвентаре.
    /// Инвентарь намеренно не знает ни о количестве, ни о цене, ни о типе
    /// игрового объекта: такие данные добавляются конкретной реализацией.
    /// </summary>
    public interface IInventoryItem
    {
        /// <summary>
        /// Стабильный идентификатор экземпляра в рамках игровой сессии.
        /// Он используется вместо позиции в списке, потому что базовое
        /// хранилище неупорядоченное.
        /// </summary>
        string ItemId { get; }

        /// <summary>
        /// Отображаемое имя. Стандартное хранилище сортирует выдачу по нему.
        /// </summary>
        string Name { get; }
    }
}
